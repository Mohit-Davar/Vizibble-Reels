# Shared tool discovery for the render scripts. Dot-source it: . "$PSScriptRoot\tools.ps1"
$ErrorActionPreference = 'Stop'
$Root = Split-Path $PSScriptRoot -Parent

function Find-Blender {
  if ($env:BLENDER -and (Test-Path $env:BLENDER)) { return $env:BLENDER }
  $cmd = Get-Command blender -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  $hit = Get-ChildItem 'C:\Program Files\Blender Foundation' -Recurse -Depth 1 -Filter blender.exe -ErrorAction SilentlyContinue |
    Sort-Object FullName -Descending | Select-Object -First 1
  if ($hit) { return $hit.FullName }
  return $null
}

function Find-Tool([string]$name) {
  $cmd = Get-Command $name -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  $hit = Get-ChildItem "$env:LOCALAPPDATA\Microsoft\WinGet\Packages" -Recurse -Filter "$name.exe" -ErrorAction SilentlyContinue |
    Select-Object -First 1
  if ($hit) { return $hit.FullName }
  return $null
}

$Blender = Find-Blender
$FFmpeg = Find-Tool 'ffmpeg'
$FFprobe = Find-Tool 'ffprobe'

function Invoke-Checked([string]$what, [scriptblock]$block) {
  Write-Host "==> $what" -ForegroundColor Cyan
  & $block
  if ($LASTEXITCODE -ne 0) { throw "$what failed (exit $LASTEXITCODE)" }
}

function Sync-Scenes {
  # Mirror Blender frames into Remotion's public folder.
  $src = Join-Path $Root 'output\scenes'
  $dst = Join-Path $Root 'remotion\public\scenes'
  robocopy $src $dst /MIR /NFL /NDL /NJH /NJS /NP | Out-Null
  if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
  $global:LASTEXITCODE = 0
  # Manifest of rendered scenes, read by Remotion at bundle time.
  $entries = foreach ($d in (Get-ChildItem $dst -Directory -ErrorAction SilentlyContinue)) {
    $n = (Get-ChildItem $d.FullName -Filter '????.png').Count
    "  '$($d.Name)': $n,"
  }
  $ts = @(
    '// GENERATED by scripts/tools.ps1 (Sync-Scenes). Do not edit by hand.',
    '// Frame counts of the Blender renders in public/scenes.',
    'export const RENDERED: Record<string, number> = {'
  ) + $entries + '};'
  $pub = Join-Path $Root 'remotion\public'
  $media = Get-ChildItem (Join-Path $pub 'audio'), (Join-Path $pub 'sfx') -Filter *.wav -ErrorAction SilentlyContinue |
    ForEach-Object { "  '$($_.Directory.Name)/$($_.Name)'," }
  $ts += @('// Audio files present in public/.', 'export const AUDIO_FILES: string[] = [') + $media + '];'
  $out = Join-Path $Root 'remotion\src\generated\scenes.ts'
  try {
    Set-Content -Path $out -Value ($ts -join "`r`n") -Encoding UTF8
  } catch {
    # If file cannot be written, keep existing scenes.ts
  }
}

function Test-Video([string]$path, [int]$width, [int]$height) {
  if (-not $FFprobe) { throw 'ffprobe not found' }
  $json = & $FFprobe -v error -show_entries 'stream=codec_type,codec_name,width,height,r_frame_rate,pix_fmt:format=duration' -of json $path | ConvertFrom-Json
  $v = $json.streams | Where-Object codec_type -eq 'video'
  $a = $json.streams | Where-Object codec_type -eq 'audio'
  $dur = [double]$json.format.duration
  $checks = [ordered]@{
    'video codec h264'   = ($v.codec_name -eq 'h264')
    "size ${width}x${height}" = ($v.width -eq $width -and $v.height -eq $height)
    'fps 30'             = ($v.r_frame_rate -eq '30/1')
    'pixel format yuv420p' = ($v.pix_fmt -eq 'yuv420p')
    'audio codec aac'    = ($a -and $a.codec_name -eq 'aac')
    'duration 44.5-45.5s' = ($dur -ge 44.5 -and $dur -le 45.5)
  }
  $ok = $true
  foreach ($k in $checks.Keys) {
    $state = if ($checks[$k]) { 'PASS' } else { $ok = $false; 'FAIL' }
    Write-Host ("  [{0}] {1}" -f $state, $k)
  }
  Write-Host ("  duration {0:N2}s, {1}x{2}, {3}, {4}" -f $dur, $v.width, $v.height, $v.codec_name, $v.r_frame_rate)
  return $ok
}
