"""Scene 3: wiring. Wires grow one at a time per config/episode.json.

    blender -b --python blender/scenes/wiring.py -- [--preview] [--still N] [--no-render]

Camera choreography (why it moves): the ESP32-S3 header pins point *down*, so
from a high camera the wire ends vanish under the board. The camera therefore
drops to a low angle on the side where 3V3 and GPIO4 are (+X), orbits to the
front for GND, and only rises again once the circuit is complete.

The script also writes remotion/src/generated/wiring-anchors.json: the screen
position of every connection point for every frame, plus whether it is
actually visible (ray cast). Remotion draws the pin callouts from it, so the
2D labels always sit on the real 3D pins. Written even with --no-render.
"""
import json
import sys
from pathlib import Path

import bpy
from bpy_extras.object_utils import world_to_camera_view

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

SCENE = next(s for s in C.EPISODE["scenes"] if s["id"] == "wiring")
FRAMES = SCENE["duration"] + C.TRANSITION
# Screen band (px) between the title and the connection chips.
BAND = (540, 1000)
WIRE = {w["id"]: w for w in C.EPISODE["wiring"]}

# (scene-local frame, azimuth, elevation). Azimuth 0 = from the front (-Y),
# positive = camera swings toward +X. Elevations of 12-15 deg keep all six
# pin ends visible (measured with a ray-cast probe); above ~30 deg GPIO4 is
# hidden under the board.
POSES = [
    (0, 24.0, 38.0),  # matches the end of the hardware scene
    (WIRE["vcc"]["drawStart"] - 6, 32.0, 14.0),  # low, on the 3V3 / GPIO4 side
    (WIRE["data"]["drawEnd"] + 4, 27.0, 15.0),  # slow drift while VCC + DATA land
    (WIRE["gnd"]["drawStart"] - 6, 4.0, 13.0),  # orbit to the front for GND
    (WIRE["gnd"]["drawEnd"] + 6, 7.0, 14.0),
    (FRAMES - 1, 12.0, 32.0),  # rise to the hero angle the final scene opens on
]
ANCHORS_OUT = C.ROOT / "remotion" / "src" / "generated" / "wiring-anchors.json"


def pose_at(local, fitted):
    """Eased interpolation between neighbouring poses (azimuth, elevation, target, distance)."""
    for (f0, a0, e0), (f1, a1, e1), (t0, d0), (t1, d1) in zip(POSES, POSES[1:], fitted, fitted[1:]):
        if local <= f1:
            t = C.progress(local, f0, f1)
            return C.lerp(a0, a1, t), C.lerp(e0, e1, t), C.lerp(t0, t1, t), C.lerp(d0, d1, t)
    _, a, e = POSES[-1]
    return a, e, *fitted[-1]


def export_anchors(scene, cam, wires):
    """Per-frame screen position + visibility of each connection point."""
    names = [w["from"]["locator"] for w in C.EPISODE["wiring"]] + [w["to"]["locator"] for w in C.EPISODE["wiring"]]
    width, height = C.EPISODE["video"]["width"], C.EPISODE["video"]["height"]
    # hide_render does not affect scene.ray_cast, so mirror it onto
    # hide_viewport while probing: undrawn wires must not occlude pins.
    animated = [o for w in wires for o in (w.obj, w.sensor_housing, *w.sensor_housing.children,
                                           w.board_housing, *w.board_housing.children)]
    frames = []
    for f in range(1, FRAMES + 1):
        scene.frame_set(f)
        for o in animated:
            o.hide_viewport = o.hide_render
        bpy.context.view_layer.update()
        depsgraph = bpy.context.evaluated_depsgraph_get()
        origin = cam.matrix_world.translation
        row = []
        for n in names:
            p = C.locator(n).matrix_world.translation
            co = world_to_camera_view(scene, cam, p)
            ray = p - origin
            hit, loc, *_ = scene.ray_cast(depsgraph, origin, ray.normalized(), distance=ray.length + C.mm(2))
            # A hit on the pin itself or its seated housing counts as visible.
            seen = (not hit) or (loc - p).length < C.mm(4.0)
            row += [round(co.x * width, 1), round((1 - co.y) * height, 1), int(seen and co.z > 0)]
        frames.append(row)
    for o in animated:
        o.hide_viewport = False
    ANCHORS_OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "$comment": "GENERATED by blender/scenes/wiring.py. Do not edit. frames[i] = Remotion scene-local frame i; "
                    "per locator (in `names` order): x px, y px, visible 0/1, at 1080x1920.",
        "names": names,
        "frames": frames,
    }
    ANCHORS_OUT.write_text(json.dumps(payload, separators=(",", ":")), encoding="utf-8")
    print(f"ANCHORS {ANCHORS_OUT} ({len(frames)} frames)")


def main():
    opts = C.parse_args()
    scene, _, _, wires = C.build_stage(opts, FRAMES, wires=True)
    cam = C.camera(scene, lens=50.0, fstop=8.0)
    for w in wires:  # fit to the finished circuit so nothing grows out of frame
        w.finished()
    bpy.context.view_layer.update()
    pts = C.hardware_points()
    base = C.mm(-6.0, -34.0, 34.0)
    fitted = [C.fit_view(scene, cam, base, az, el, BAND, pts=pts) for _, az, el in POSES]
    for f in range(1, FRAMES + 1):
        az, el, target, dist = pose_at(f - 1, fitted)
        C.key_camera(cam, f, C.orbit_position(target, dist, az, el), target)
        for wire in wires:
            # Config frames are 0-based scene-local; Blender frames start at 1.
            wire.keyframe(f, wire.spec["drawStart"] + 1, wire.spec["drawEnd"] + 1)
    export_anchors(scene, cam, wires)
    C.finish(scene, SCENE["folder"], opts["preview"], opts["still"], opts["no_render"])


main()
