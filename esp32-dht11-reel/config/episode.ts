export const scene = (id: SceneId): Scene => {
  const s = SCENES.find((x) => x.id === id);
  if (!s) throw new Error(`Unknown scene ${id}`);
  return s;
};

// ---------------------------------------------------------------- firmware
export const FIRMWARE: string = firmware.replace(/\r\n/g, '\n');
const LINES = FIRMWARE.split('\n');

/** Slice 1-based inclusive line range from the real sketch and dedent it. */
const slice = (from: number, to: number) => {
  const lines = LINES.slice(from - 1, to);
  const indent = Math.min(
    ...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)![0].length),
  );
  return { startLine: from, code: lines.map((l) => l.slice(indent)).join('\n') };
};

export type CodeSegment = {
  id: string;
  heading: string;
  startLine: number;
  code: string;
  /**
   * Pointer callouts: `token` is the exact text on `line` (1-based, within the
   * segment) that gets underlined, with `text` shown beneath it.
   */
  annotations: { line: number; token: string; text: string }[];
  /** Scene-local frame the segment appears. Synced to config/narration.ts. */
  at: number;
};

